BUNDLE_FILES = ("Dockerfile", "compose.yaml", "plan.json")
SENSITIVE_CATEGORIES = {"environment file", "key or credential file", "registry or login config"}


@dataclass
class BundleResult:
    path: Path
    status: str
    project: str | None
    bundle_id: str | None


def slugify(name: str, limit: int = 24) -> str:
    slug = re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")[:limit].strip("-")
    return slug or "app"


def make_identity(insp: Inspection) -> tuple[str, str, str]:
    """Return (bundle_id, compose project name, image name)."""
    src = insp.source
    if src.kind == "remote" and src.url:
        base = src.url.rstrip("/").rsplit("/", 1)[-1]
    else:
        base = Path(src.path or "app").name
        if insp.app_root not in {".", ""}:
            base = Path(insp.app_root).name
    bundle_id = secrets.token_hex(4)
    project = f"r2t-{slugify(base)}-{bundle_id}"
    return bundle_id, project, f"r2t/{project}:latest"


# ---- Dockerfile ---------------------------------------------------------------------------


def _exec_form(argv: list[str]) -> str:
    return json.dumps(argv)


def render_dockerfile(insp: Inspection, bundle_id: str) -> str:
    assert insp.base_image and insp.container_port and insp.start_argv  # noqa: S101
    install = shlex.join(insp.install_argv)
    lines = [
        f"# Generated by r2t {__version__} (bundle {bundle_id}). Review before building.",
        "# Building runs the dependency install below; starting the container runs repo code.",
        f"FROM {insp.base_image}",
    ]
    if insp.stack == "node":
        if insp.framework == "next":
            lines.append("ENV NEXT_TELEMETRY_DISABLED=1")
        if insp.package_manager == "pnpm":
            lines += [
                "# pnpm is installed with npm because the node:26 image does not ship corepack.",
                f"RUN npm install --global pnpm@{insp.package_manager_version}",
            ]
        lines += [
            "RUN mkdir -p /app && chown node:node /app",
            "WORKDIR /app",
            "USER node",
            "COPY --chown=node:node source/ ./",
            f"RUN {install}",
        ]
    else:
        lines += [
            "ENV PYTHONDONTWRITEBYTECODE=1 \\",
            "    PYTHONUNBUFFERED=1 \\",
            "    PIP_NO_CACHE_DIR=1 \\",
            "    PIP_DISABLE_PIP_VERSION_CHECK=1 \\",
            "    PATH=/opt/venv/bin:$PATH",
            "RUN useradd --create-home --uid 1000 app \\",
            " && python -m venv /opt/venv \\",
            " && chown -R app:app /opt/venv \\",
            " && mkdir -p /app && chown app:app /app",
            "WORKDIR /app",
            "USER app",
            "COPY --chown=app:app source/ ./",
            f"RUN {install}",
        ]
    lines += [f"EXPOSE {insp.container_port}", f"CMD {_exec_form(insp.start_argv)}", ""]
    return "\n".join(lines)


def render_dockerignore() -> str:
    return (
        "# Only source/ (and the Dockerfile) may enter the build context.\n"
        "# This keeps .env, plan.json and REPORT.md out of the image.\n"
        "*\n"
        "!source\n"
        "!Dockerfile\n"
    )


# ---- compose.yaml -------------------------------------------------------------------------


def render_compose(insp: Inspection, project: str, image: str, bundle_id: str) -> str:
    port = insp.container_port
    q = json.dumps  # JSON strings are valid YAML double-quoted scalars
    return "\n".join(
        [
            f"# Generated by r2t {__version__} (bundle {bundle_id}). Review before running.",
            "# Create ./.env from .env.template if the app needs environment variables;",
            "# .env is read at run time and is never copied into the image.",
            f"name: {q(project)}",
            "services:",
            "  app:",
            "    build:",
            "      context: .",
            "      dockerfile: Dockerfile",
            f"    image: {q(image)}",
            "    labels:",
            f"      dev.r2t.bundle: {q(bundle_id)}",
            "    init: true",
            "    ports:",
            f"      - {q(f'127.0.0.1:${{R2T_HOST_PORT:-{port}}}:{port}')}",
            "    env_file:",
            "      - path: .env",
            "        required: false",
            "    security_opt:",
            "      - no-new-privileges:true",
            "    cap_drop:",
            "      - ALL",
            '    restart: "no"',
            "",
        ]
    )


def render_env_template(insp: Inspection) -> str:
    lines = [
        "# r2t: variable names found in the repository's example env files. Values are empty",
        "# on purpose. To use: cp .env.template .env, fill in what the app needs, then r2t run.",
        "# .env is read by Docker Compose at run time and never copied into the image.",
    ]
    lines += [f"{e.name}=" for e in insp.env_names]
    return "\n".join(lines) + "\n"


# ---- reproducibility honesty --------------------------------------------------------------


def variation_and_pinned(insp: Inspection) -> tuple[list[str], list[str]]:
    varies: list[str] = []
    pinned: list[str] = []
    if insp.base_image:
        varies.append(
            f"Base image `{insp.base_image}` is referenced by tag, not by digest; the tag moves."
        )
    if insp.package_manager == "pnpm":
        if (
            insp.detection("pnpm_version")
            and insp.detection("pnpm_version").evidence[0].kind == "file"
        ):  # type: ignore[union-attr]
            pinned.append(f"pnpm {insp.package_manager_version} (from package.json#packageManager)")
        else:
            varies.append(
                f"pnpm {insp.package_manager_version} was chosen by r2t; the repo does not pin it."
            )
    elif insp.package_manager == "npm":
        varies.append("The npm version comes from the Node base image; the repo does not pin it.")
    if insp.stack == "python":
        varies.append("The pip version comes from the Python base image; the repo does not pin it.")
    if insp.lock_status == "locked":
        pinned.append(
            f"Dependency versions are fixed by {insp.lockfile or 'the requirement hashes'}."
        )
    elif insp.lock_status and insp.lock_status.startswith("direct pins"):
        varies.append("Only direct dependencies are pinned; transitive dependencies are unlocked.")
    elif insp.lock_status == "unlocked":
        varies.append("Dependencies are unlocked: versions are resolved when the image is built.")
    varies.append(
        "Dependencies are downloaded from the network at build time "
        "(registries can change or remove packages)."
    )
    varies.append(
        "The app runs in development-server mode; behavior and first-request timing differ "
        "from a production build."
    )
    src = insp.source
    if src.resolved_commit:
        pinned.append(f"Source commit {src.resolved_commit}.")
    pinned.append(f"Source snapshot digest sha256:{src.snapshot_digest}.")
    pinned.append("Dockerfile and compose.yaml content (sha256 recorded in plan.json).")
    return varies, pinned


# ---- plan.json and REPORT.md --------------------------------------------------------------


def sha256_text(text: str) -> str:
    return hashlib.sha256(text.encode()).hexdigest()


def build_plan(
    insp: Inspection,
    bundle_id: str | None,
    project: str | None,
    image: str | None,
    dockerfile: str | None,
    compose: str | None,
) -> dict:
    data = insp.to_dict()
    varies, pinned = variation_and_pinned(insp)
    supported = insp.status == SUPPORTED
    commands = data["commands"]
    if supported and project:
        base = ["docker", "compose", "-p", project, "-f", "compose.yaml"]
        commands["build"] = [*base, "build"]
        commands["up"] = [*base, "up", "-d"]
    data.update(
        {
            "bundle_id": bundle_id,
            "compose_project": project,
            "image": image,
            "files": {
                "dockerfile_sha256": sha256_text(dockerfile) if dockerfile else None,
                "compose_sha256": sha256_text(compose) if compose else None,
            },
            "variation_sources": varies,
            "pinned": pinned,
        }
    )
    assert data["schema_version"] == SCHEMA_VERSION  # noqa: S101
    return data


def _bullets(items: list[str], empty: str = "None.") -> list[str]:
    return [f"- {i}" for i in items] if items else [empty]


def render_report(insp: Inspection, plan: dict, output_name: str) -> str:
    src = insp.source
    out: list[str] = [f"# r2t report: {insp.status}", ""]
    out.append(
        "Generated by r2t. This is a description of what r2t found and decided, with the "
        "evidence behind each item. It does not claim the app works or that the build is "
        "reproducible."
    )
    out.append("")
    out.append("## Source")
    if src.kind == "remote":
        out += [
            f"- Repository: {code_span(src.url)}",
            f"- Requested ref: {code_span(src.requested_ref or '(default branch)')}",
            f"- Resolved commit: {code_span(src.resolved_commit)}",
        ]
    else:
        out += [f"- Local path: {code_span(src.path)}"]
        if src.git_head:
            out.append(f"- Git HEAD: {code_span(src.git_head)}")
        if src.dirty is not None:
            out.append(
                f"- Working tree dirty (including untracked files): {'yes' if src.dirty else 'no'}"
            )
        if src.git_note:
            out.append(f"- Git note: {clean(src.git_note)}")
    if insp.app_root != ".":
        out.append(f"- App root inside the repository: {code_span(insp.app_root)}")
    out.append(
        f"- Snapshot digest: {code_span('sha256:' + str(src.snapshot_digest))} "
        "(authoritative identity of the files copied into `source/`)"
    )
    out.append("- Evidence paths below are relative to the app root (the bundle's `source/`).")
    out.append("")

    out.append("## Launch plan")
    if insp.status == SUPPORTED:
        lock = insp.lock_status or "n/a"
        out += [
            f"- Stack: {insp.stack} / {insp.framework}",
            f"- Base image: {code_span(insp.base_image)}",
            f"- Package manager: {insp.package_manager or 'pip'}"
            + (f" {insp.package_manager_version}" if insp.package_manager_version else ""),
            f"- Lock status: {lock}",
            f"- Install: {code_span(shlex.join(insp.install_argv))}",
            f"- Start: {code_span(shlex.join(insp.start_argv))}",
            f"- Container port: {insp.container_port}; readiness path "
            f"{code_span(insp.readiness_path)}",
            f"- Compose project: {code_span(plan['compose_project'])}; "
            f"image {code_span(plan['image'])}",
            f"- Run it: {code_span(f'r2t run {shlex.quote(output_name)}')}",
        ]
    else:
        out.append("No launch bundle was generated because the target is not supported yet.")
    out.append("")

    if insp.blockers:
        out.append("## Blockers")
        for b in insp.blockers:
            flag = f" Resolve with {code_span(b.flag)}." if b.flag else ""
            out.append(f"- **{b.status}**: {clean(b.reason, 600)}.{flag}")
        out.append("")
    if insp.candidates:
        out.append("## Candidates")
        for c in insp.candidates:
            out.append(
                f"- {code_span(c.get('flag', ''))} ({clean(c.get('kind') or c.get('file') or '')})"
            )
        out.append("")

    out.append("## Detections and evidence")
    for d in insp.detections:
        refs = ", ".join(code_span(e.ref()) for e in d.evidence) or "n/a"
        out.append(f"- {d.key}: {code_span(d.value)} <- {refs}")
    if not insp.detections:
        out.append("- None.")
    out.append("")

    out.append("## Assumptions")
    out += _bullets([clean(a, 600) for a in insp.assumptions])
    out.append("")

    out.append("## Scripts that will execute")
    out.append(
        "Dependency installation and app startup execute repository code. Docker is an "
        "isolation boundary, not a guarantee that arbitrary code is safe."
    )
    for s in insp.lifecycle:
        out.append(f"- [{s.when}] {code_span(s.name)}: {code_span(s.command)} ({s.evidence.ref()})")
    if insp.stack == "node":
        out.append(
            "- Installed dependencies may run their own install scripts: npm does by default; "
            "recent pnpm versions skip them unless the repo allows them."
        )
    out.append("")

    out.append("## Environment variable names")
    out.append("Names only. Values are never read into this report.")
    out += _bullets([f"{code_span(e.name)} ({e.file}:{e.line})" for e in insp.env_names])
    out.append("")

    out.append("## External services or configuration that may need manual setup")
    out += _bullets([f"{clean(s.why, 400)} ({s.evidence.ref()})" for s in insp.services])
    out.append("")

    out.append("## Existing container files (evidence only; r2t does not use them)")
    out += _bullets([e.ref() for e in insp.container_files])
    out.append("")

    out.append("## Excluded from the snapshot")
    sensitive = [x for x in insp.excluded if x["category"] in SENSITIVE_CATEGORIES]
    other: dict[str, int] = {}
    for x in insp.excluded:
        if x["category"] not in SENSITIVE_CATEGORIES:
            other[x["category"]] = other.get(x["category"], 0) + 1
    out += _bullets([f"{code_span(x['path'])}: {x['category']}" for x in sensitive], "")
    out += _bullets([f"{n} path(s): {cat}" for cat, n in sorted(other.items())], "")
    out.append("")
    if insp.skipped_symlinks:
        out.append("## Symlinks that were not followed or copied")
        out += [f"- {code_span(x['path'])}: {x['reason']}" for x in insp.skipped_symlinks]
        out.append("")
    if insp.notes:
        out.append("## Notes")
        out += _bullets([clean(n, 600) for n in insp.notes])
        out.append("")

    out.append("## Sources of variation")
    out.append("r2t does not claim this output is reproducible. What can differ between builds:")
    out += _bullets(plan["variation_sources"])
    out.append("")
    out.append("What is pinned:")
    out += _bullets(plan["pinned"])
    out.append("")
    return "\n".join(out)


# ---- atomic bundle writer -----------------------------------------------------------------


def _inside(path: Path, parent: Path) -> bool:
    return path == parent or parent in path.parents


def write_bundle(
    insp: Inspection, snap: Snapshot, output: Path, repo_root: Path | None = None
) -> BundleResult:
    out = Path(os.path.abspath(output.expanduser()))
    if out.exists() or out.is_symlink():
        raise InputError(
            f"output path already exists: {out}",
            "choose a new directory; r2t never writes into an existing one",
        )
    parent = out.parent.resolve()
    target = parent / out.name
    for forbidden in {snap.root, (repo_root or snap.root).resolve()}:
        if _inside(target, forbidden):
            raise InputError(
                "the output directory must be outside the source being inspected",
                f"{target} is inside {forbidden}",
            )
    tmp = parent / f".{out.name}.r2t-tmp-{secrets.token_hex(4)}"
    try:
        parent.mkdir(parents=True, exist_ok=True)
        tmp.mkdir()
    except OSError as exc:
        raise InputError(f"cannot create the output directory: {exc.strerror or exc}") from exc
    try:
        supported = insp.status == SUPPORTED
        bundle_id = project = image = dockerfile = compose = None
        if supported:
            bundle_id, project, image = make_identity(insp)
            dockerfile = render_dockerfile(insp, bundle_id)
            compose = render_compose(insp, project, image, bundle_id)
        plan = build_plan(insp, bundle_id, project, image, dockerfile, compose)
        if supported:
            materialize(snap, tmp / "source")
            (tmp / "Dockerfile").write_text(dockerfile)  # type: ignore[arg-type]
            (tmp / "compose.yaml").write_text(compose)  # type: ignore[arg-type]
            (tmp / ".dockerignore").write_text(render_dockerignore())
        (tmp / ".env.template").write_text(render_env_template(insp))
        (tmp / "plan.json").write_text(json.dumps(plan, indent=2) + "\n")
        (tmp / "REPORT.md").write_text(render_report(insp, plan, out.name))
        os.rename(tmp, target)
    except BaseException:
        shutil.rmtree(tmp, ignore_errors=True)
        raise
    return BundleResult(target, insp.status, project, bundle_id)
